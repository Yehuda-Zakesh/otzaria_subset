/// בונה URI של SQLite שמחבר קובץ **לקריאה בלבד**.
///
/// ## למה זה נחוץ
///
/// ‏SQLite מוריש את דגל הקריאה-בלבד מהחיבור הראשי לכל מה שמחובר אליו
/// ב-`ATTACH`. לכן חיבור שנפתח `readOnly` אינו יכול לכתוב גם למסד מחובר
/// **כתיב** — הניסיון נכשל ב-`SQLITE_READONLY` (code 8). ההשלכה: מנוע
/// שקורא ממסד אחד וכותב לאחר חייב לפתוח את **היעד** כראשי ולחבר את
/// **המקור**, ולא להיפך.
///
/// זה מעמיד את מסד המשתמש בעמדה כתיבה, וזה בדיוק מה שאסור: `seforim.db`
/// שלו הוא 7.4GB שלא ניתן לשחזר בלי הורדה מחדש. ה-URI כאן מחזיר את
/// ההגנה — `mode=ro` הופך את המסד המחובר לקריאה בלבד בפני עצמו, ללא תלות
/// בדגל של החיבור הראשי.
///
/// **דורש `uri: true` בפתיחת החיבור הראשי.** בלעדיו SQLite מתייחס
/// למחרוזת כשם קובץ מילולי, מחפש קובץ בשם `file:C:/...?mode=ro` ונכשל
/// ביצירת מסד ריק חדש — כלומר שקט, לא רועש. ראו `SubsetBuilder`.
library;

/// ‏URI לקריאה בלבד עבור [path].
///
/// ‏`Uri.file` מטפל בהמרה לנתיב URI חוקי, כולל קידוד רווחים (`%20`) —
/// שהוא המקרה הרגיל כאן, כי הנתיב עובר דרך תיקיית המשתמש בווינדוס.
String readOnlyUri(String path) => '${Uri.file(path)}?mode=ro';

/// ‏URI immutable — לקריאה בלבד **וללא** יצירת קובצי `-wal`/`-shm`.
///
/// מתאים לכונן מוגן-כתיבה או ל-CD: SQLite מבטיח לא לגעת בקובץ כלל.
/// **אין להשתמש בו על מסד שתהליך אחר עשוי לכתוב אליו במקביל** — SQLite
/// מדלג אז על בדיקות שינוי ויקרא נתונים לא עקביים.
String immutableUri(String path) => '${Uri.file(path)}?immutable=1';
